-- 006_mission_is_active.sql
-- Флаг видимости миссии для админки.
--
-- Админ может «спрятать» миссию, не удаляя её: is_active = 0. Неактивная миссия
-- по-прежнему видна в списке админки (с «глазиком»-переключателем на карточке),
-- но её следует исключать из всего, что показывается ученику. Существующие
-- миссии по умолчанию активны.
--
-- Идемпотентно не бывает у ADD COLUMN — накатывать один раз.
-- ============================================================================

ALTER TABLE missions
  ADD COLUMN is_active TINYINT(1) NOT NULL DEFAULT 1;
